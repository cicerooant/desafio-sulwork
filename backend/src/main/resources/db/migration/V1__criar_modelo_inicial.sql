CREATE TABLE evento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    descricao VARCHAR(2000),
    tipo VARCHAR(60) NOT NULL,
    data_hora TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    prazo_alteracao TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    status VARCHAR(20) NOT NULL,
    CONSTRAINT ck_evento_status CHECK (
        status IN ('RASCUNHO', 'ABERTO', 'ENCERRADO', 'REALIZADO', 'CANCELADO')
    )
);

CREATE TABLE colaborador (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    cpf VARCHAR(11) NOT NULL UNIQUE,
    CONSTRAINT ck_colaborador_cpf_formato CHECK (cpf ~ '^[0-9]{11}$')
);

CREATE TABLE inscricao_evento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id BIGINT NOT NULL REFERENCES evento (id),
    colaborador_id BIGINT NOT NULL REFERENCES colaborador (id),
    CONSTRAINT uk_inscricao_evento_colaborador UNIQUE (evento_id, colaborador_id)
);

CREATE TABLE colaborador_restricao (
    colaborador_id BIGINT NOT NULL REFERENCES colaborador (id),
    restricao VARCHAR(30) NOT NULL,
    CONSTRAINT ck_colaborador_restricao_codigo CHECK (
        restricao IN (
            'SEM_GLUTEN', 'SEM_LACTOSE', 'SEM_LEITE', 'SEM_AMENDOIM',
            'SEM_CASTANHAS', 'SEM_SOJA', 'SEM_OVO', 'SEM_PEIXE',
            'SEM_CRUSTACEOS', 'SEM_GERGELIM', 'VEGETARIANO', 'VEGANO'
        )
    ),
    PRIMARY KEY (colaborador_id, restricao)
);

CREATE TABLE categoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id BIGINT NOT NULL REFERENCES evento (id),
    nome VARCHAR(100) NOT NULL,
    meta_quantidade INTEGER NOT NULL,
    CONSTRAINT ck_categoria_meta_positiva CHECK (meta_quantidade > 0),
    CONSTRAINT uk_categoria_evento_nome UNIQUE (evento_id, nome)
);

CREATE TABLE item_evento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria_id BIGINT NOT NULL REFERENCES categoria (id),
    nome VARCHAR(120) NOT NULL,
    quantidade_necessaria INTEGER NOT NULL,
    obrigatorio BOOLEAN NOT NULL,
    CONSTRAINT ck_item_quantidade_positiva CHECK (quantidade_necessaria > 0)
);

CREATE TABLE item_alergeno (
    item_id BIGINT NOT NULL REFERENCES item_evento (id),
    alergeno VARCHAR(30) NOT NULL,
    CONSTRAINT ck_item_alergeno_codigo CHECK (
        alergeno IN (
            'GLUTEN', 'LEITE', 'LACTOSE', 'AMENDOIM', 'CASTANHAS',
            'SOJA', 'OVO', 'PEIXE', 'CRUSTACEOS', 'GERGELIM'
        )
    ),
    PRIMARY KEY (item_id, alergeno)
);

CREATE TABLE contribuicao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inscricao_evento_id BIGINT NOT NULL REFERENCES inscricao_evento (id),
    item_id BIGINT NOT NULL REFERENCES item_evento (id),
    quantidade INTEGER NOT NULL,
    CONSTRAINT ck_contribuicao_quantidade_positiva CHECK (quantidade > 0)
);

CREATE INDEX idx_inscricao_evento_colaborador ON inscricao_evento (colaborador_id);
CREATE INDEX idx_categoria_evento ON categoria (evento_id);
CREATE INDEX idx_item_categoria ON item_evento (categoria_id);
CREATE INDEX idx_contribuicao_inscricao ON contribuicao (inscricao_evento_id);
CREATE INDEX idx_contribuicao_item ON contribuicao (item_id);
